import { NextRequest, NextResponse } from 'next/server'
import { callGemma } from '@/lib/ai'
import { SYSTEM_PROMPTS } from '@/lib/prompts'

export async function POST(req: NextRequest) {
  try {
    const { question, offerDocument } = await req.json()

    if (!question || !offerDocument) {
      return NextResponse.json(
        { error: 'Question and offerDocument are required' },
        { status: 400 }
      )
    }

    // Attempt Google Gemma 4 (31B) via OpenRouter
    const gemmaResponse = await callGemma({
      system: SYSTEM_PROMPTS.investorQA,
      messages: [
        {
          role: 'user',
          content: `Offer Document:\n${offerDocument}\n\nQuestion: ${question}`,
        },
      ],
      max_tokens: 1024,
    })

    if (gemmaResponse) {
      return NextResponse.json({ response: gemmaResponse })
    }

    // Smart context-aware fallback if API key is not configured or network offline:
    const qLower = question.toLowerCase()
    let responseText = ''

    if (qLower.includes('close') || qLower.includes('shut') || qLower.includes('fails') || qLower.includes('loss')) {
      responseText =
        'If the business permanently closes or underperforms, payouts cease since this is a pure revenue-share instrument. Remaining business assets would be liquidated with senior creditors paid first. You may lose part or all of your invested capital.'
    } else if (qLower.includes('when') && (qLower.includes('return') || qLower.includes('payout') || qLower.includes('money'))) {
      responseText =
        'Returns are distributed on a monthly basis directly to your registered bank account, starting the first calendar month after the expanded outlet commences commercial operations.'
    } else if (qLower.includes('withdraw') || qLower.includes('exit') || qLower.includes('cancel')) {
      responseText =
        'There is no early withdrawal option. Your capital is committed for the full duration specified in the terms (e.g. 36 months). You may only transfer your stake to another registered investor subject to platform approval.'
    } else if (qLower.includes('insur') || qLower.includes('guarantee') || qLower.includes('safe')) {
      responseText =
        'No. This investment is not insured by DICGC, RBI, or any government scheme. Returns depend solely on the actual monthly revenues generated by the business.'
    } else if (qLower.includes('minimum') || qLower.includes('ticket')) {
      responseText =
        'The minimum ticket size for this campaign is specified in the terms (typically ₹10,000), making it accessible for community regulars.'
    } else {
      const words = qLower.split(' ').filter((w: string) => w.length > 4)
      const found = words.some((w: string) => offerDocument.toLowerCase().includes(w))
      if (found) {
        responseText =
          'According to the offer document, all expansion expenditures and operational disbursements are governed strictly by the revenue-share agreement. For personalized queries, feel free to reach out to the owner directly through CafeStake.'
      } else {
        responseText = "That isn't covered in this offer. Please ask the business owner."
      }
    }

    return NextResponse.json({ response: responseText })
  } catch (error: any) {
    console.error('Investor QA error:', error)
    return NextResponse.json(
      { error: error.message || 'Failed to get answer' },
      { status: 500 }
    )
  }
}
